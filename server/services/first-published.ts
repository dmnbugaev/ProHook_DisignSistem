import type { CatalogSnapshot } from "./moysklad";

/**
 * Реестр «первой публикации» товара на сайте: productId → дата, когда товар
 * впервые появился в снимке каталога. Дата фиксируется один раз и больше не
 * меняется — правки товара в МойСклад (цена, описание, фото, остатки) не
 * поднимают его в «Новинках» (решение владельца 20.10.2026, доведено до
 * работающего состояния 11.11.2026).
 *
 * Почему не дата создания из МойСклад: поле created в списке
 * entity/product фактически не приходит (снимок от 05.11.2026: дата
 * публикации совпадала с updated у всех 2636 товаров с фото), и фолбэк на
 * updated делал «новинкой» любой отредактированный товар. Реестр же
 * зависит только от состояния сайта и работает независимо от МойСклад.
 *
 * Реестр никогда не сокращается: товар, временно скрытый в МойСклад
 * («Показать на сайте» = нет) и вернувшийся, сохраняет исходную дату и не
 * становится новинкой второй раз. Рост — ~100 байт на товар за жизнь
 * учётной записи, несущественно.
 *
 * Хранится в снимке рядом с stockDetail (server-only, в API не публикуется).
 * Первый запуск после внедрения — холодный старт: все существующие товары
 * получают один штамп момента обновления, то есть «новинками» считаются
 * только товары, добавленные в МойСклад уже после внедрения реестра.
 */
export function applyFirstPublished(
  next: CatalogSnapshot,
  previous?: CatalogSnapshot,
): CatalogSnapshot {
  const registry: Record<string, string> = { ...previous?.firstPublished };
  // Один штамп на весь цикл обновления: впервые увиденные в этом снимке
  // товары считаются поступившими одновременно; порядок внутри партии
  // выравнивается по названию в репозитории каталога.
  const seenAt = new Date().toISOString();
  for (const product of next.products) {
    const known = registry[product.id];
    product.firstPublishedAt = known ?? seenAt;
    if (!known) registry[product.id] = seenAt;
  }
  next.firstPublished = registry;
  return next;
}
